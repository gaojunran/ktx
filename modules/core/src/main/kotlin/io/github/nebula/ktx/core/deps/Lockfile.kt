package io.github.nebula.ktx.core.deps

import org.tomlj.Toml
import java.nio.file.Path
import kotlin.io.path.bufferedReader
import kotlin.io.path.bufferedWriter
import kotlin.io.path.exists

/**
 * Lockfile contents.
 *
 * Design principle: **record resolution results, don't redo resolution**.
 *   - `directs`: for each top-level `@file:DependsOn(coord)` declaration, the
 *     list of jar files (including transitive deps), as paths relative to
 *     `~/.m2/repository` in m2 layout.
 *   - `repositories`: the repository URLs declared via `@file:Repository(...)`,
 *     captured for minimal reproducibility tracking in frozen mode (not used
 *     for re-downloads at present).
 *
 * Why m2-relative paths instead of coordinates: the local Aether repository is
 * already in m2 layout, so frozen mode only needs to join the relative path
 * onto `~/.m2/repository/` to find the jar — no re-resolution, no network.
 * This is the core lever in Phase 1.2 that compresses "8 seconds on the second
 * run" down to sub-second.
 *
 * Cross-machine / CI: on the first run, ktx downloads into the local repository,
 * and the lockfile gets committed. On another machine, `kts run --frozen` is
 * instant if the local repo already has the same coordinates (e.g. CI maven
 * cache); if jars are missing, an error is raised asking the user to warm up
 * with a non-frozen run first (same semantics as `uv lock` + `uv run`).
 *
 * @property scriptHash sha256 of the script source; frozen mode verifies the
 *   source hasn't drifted.
 * @property directs map from top-level `@file:DependsOn` coordinates to relative
 *   path lists (including transitives).
 * @property repositories list of `@file:Repository` URLs.
 */
data class Lockfile(
    val scriptHash: String,
    val directs: Map<String, List<String>>,
    val repositories: List<String>,
) {
    companion object {
        const val SCHEMA_VERSION = 1
        const val FILENAME_SUFFIX = ".lock"

        /** Returns the lockfile path for a given script: same directory, with `.lock` appended. */
        fun pathFor(scriptPath: Path): Path =
            scriptPath.resolveSibling(scriptPath.fileName.toString() + FILENAME_SUFFIX)

        fun read(path: Path): Lockfile? {
            if (!path.exists()) return null
            val parsed = path.bufferedReader().use { Toml.parse(it) }
            if (parsed.hasErrors()) {
                throw IllegalStateException(
                    "failed to parse lockfile: ${path.toAbsolutePath()}\n" +
                        parsed.errors().joinToString("\n") { "  - $it" },
                )
            }
            val schema = parsed.getLong("schema") ?: 0L
            require(schema == SCHEMA_VERSION.toLong()) {
                "unsupported lockfile schema version $schema (expected $SCHEMA_VERSION)"
            }
            val scriptHash = parsed.getString("script.hash").orEmpty()
            val directs = mutableMapOf<String, List<String>>()
            val directsArr = parsed.getArray("directs")
            if (directsArr != null) {
                for (i in 0 until directsArr.size()) {
                    val entry = directsArr.getTable(i)
                    val coord = entry.getString("coordinates") ?: continue
                    val filesArr = entry.getArray("files") ?: continue
                    directs[coord] = (0 until filesArr.size()).map { filesArr.getString(it) }
                }
            }
            val repositories = parsed.getArray("repositories")?.let { arr ->
                (0 until arr.size()).map { arr.getString(it) }
            }.orEmpty()
            return Lockfile(scriptHash, directs, repositories)
        }
    }

    fun write(path: Path) {
        path.bufferedWriter().use { w ->
            w.appendLine("# Auto-generated by ktx. Do not edit by hand.")
            w.appendLine("schema = $SCHEMA_VERSION")
            // Top-level `repositories` must be written before any [table] —
            // once TOML enters a table, every subsequent key belongs to it
            // until the next [...] header.
            if (repositories.isNotEmpty()) {
                w.appendLine("repositories = [")
                for (r in repositories) w.appendLine("  ${quoteToml(r)},")
                w.appendLine("]")
            }
            w.appendLine()
            w.appendLine("[script]")
            w.appendLine("hash = ${quoteToml(scriptHash)}")
            w.appendLine()
            // Sorted: keeps lockfile output stable across re-locks (diff-friendly).
            for ((coord, files) in directs.toSortedMap()) {
                w.appendLine("[[directs]]")
                w.appendLine("coordinates = ${quoteToml(coord)}")
                w.appendLine("files = [")
                for (f in files.sorted()) w.appendLine("  ${quoteToml(f)},")
                w.appendLine("]")
                w.appendLine()
            }
        }
    }
}

/**
 * TOML basic-string escape. The strings we emit are paths and coordinates,
 * with controlled character sets, so a full TOML writer dependency isn't justified.
 */
internal fun quoteToml(s: String): String =
    "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
